export function initializeSeedData() {
  try {
    // Check if data already exists
    const existingWarehouses = localStorage.getItem("inventory_warehouses");
    if (existingWarehouses) {
      console.log("Seed data already initialized");
      return; // Already seeded
    }

    // Save all seed data
    localStorage.setItem(
      "inventory_warehouses",
      JSON.stringify(SEED_WAREHOUSES)
    );
    localStorage.setItem("inventory_items", JSON.stringify(SEED_INVENTORY));
    localStorage.setItem("inventory_transfers", JSON.stringify(SEED_TRANSFERS));

    console.log("✓ Seed data initialized successfully");
    console.log(
      `  - ${SEED_WAREHOUSES.length} warehouses`
    );
    console.log(`  - ${SEED_INVENTORY.length} inventory items`);
    console.log(`  - ${SEED_TRANSFERS.length} transfers`);
  } catch (error) {
    console.error("Failed to initialize seed data:", error);
  }
}
